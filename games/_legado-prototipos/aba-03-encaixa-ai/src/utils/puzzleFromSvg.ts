/**
 * Parses an SVG string containing named paths (id, fill, d) into a playable PuzzleTheme.
 * Allows supervisors/therapists to import new puzzle themes without touching code.
 */
export function parseSvgToTheme(
  svgContent: string,
  themeId: string,
  themeName: string,
  level: number = 3
): PuzzleTheme {
  const parser = new DOMParser();
  const doc = parser.parseFromString(svgContent, 'image/svg+xml');
  const svgEl = doc.querySelector('svg');

  const widthAttr = svgEl?.getAttribute('width') || '700';
  const heightAttr = svgEl?.getAttribute('height') || '380';
  const boardWidth = parseInt(widthAttr, 10) || 700;
  const boardHeight = parseInt(heightAttr, 10) || 380;

  const pathNodes = doc.querySelectorAll('path[id]');
  const pieces: PuzzlePieceDef[] = [];

  const defaultColors = ['#E63946', '#2A9D8F', '#F4A261', '#457B9D', '#E76F51', '#2D6A4F'];

  pathNodes.forEach((node, index) => {
    const id = node.getAttribute('id') || `piece-${index + 1}`;
    const name = node.getAttribute('data-name') || id.replace(/[-_]/g, ' ');
    const d = node.getAttribute('d') || '';
    const fill = node.getAttribute('fill') || defaultColors[index % defaultColors.length];

    // Compute approximate coordinates or spread evenly if not positioned
    const col = index % 3;
    const row = Math.floor(index / 3);
    const targetX = 140 + col * 200;
    const targetY = 120 + row * 140;

    pieces.push({
      id,
      name,
      color: fill,
      accentColor: '#FFFFFF',
      pathD: d,
      viewBox: '0 0 140 140',
      width: 130,
      height: 130,
      targetX,
      targetY,
      targetAngle: 0,
      pegPosition: { x: 65, y: 65 },
    });
  });

  return {
    id: themeId,
    name: themeName,
    description: `Quebra-cabeça importado via SVG (${pieces.length} peças).`,
    level,
    boardWidth,
    boardHeight,
    pieces: pieces.length > 0 ? pieces : BUILT_IN_THEMES[0].pieces,
  };
}
